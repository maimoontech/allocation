import type { SelectOption } from "../../../components/ui/Select";
import type { LookupValue, MemberLookups, MemberProfile } from "../../../features/member/memberApi";

/**
 * Shared types and helpers for the twelve tab components.
 *
 * `TabProps` lives here rather than in Tab 1 so the tabs do not import from each other —
 * the earlier arrangement had Tab 3 importing its props type from Tab 1, which implied a
 * relationship that does not exist.
 */

export type TabProps = {
  /** Saved values overlaid with unsaved edits — what the member should see. */
  value: MemberProfile;
  lookups: MemberLookups;
  errorFor: (field: string) => string | undefined;
  /**
   * `field` is a profile column, or the literal `"__fields__"` with an object value to apply
   * several at once. Several-at-once matters for a conditional rule that clears its
   * dependents: both changes land in one update and cannot be seen half-applied.
   */
  onChange: (field: string, value: unknown) => void;
  disabled?: boolean;
};

/**
 * Turns a lookup list into Select options, marking anything still awaiting review.
 *
 * FR-094: a draft value must not read as authoritative. FR-095: an empty list says so rather
 * than presenting an empty dropdown that looks broken.
 */
export function lookupOptions(
  list: LookupValue[],
  placeholder = "Select..."
): SelectOption[] {
  return [
    { value: "", label: list.length ? placeholder : "No options available" },
    ...list.map((item) => ({
      value: String(item.id),
      label: item.is_draft ? `${item.name}  (DRAFT — NEEDS REVIEW)` : item.name
    }))
  ];
}

/** Options for a plain string enum, with a leading placeholder. */
export function enumOptions(values: readonly string[], placeholder = "Select..."): SelectOption[] {
  return [{ value: "", label: placeholder }, ...values.map((v) => ({ value: v, label: v }))];
}

/**
 * The floor for every Hijri year the member picks on Tabs 2, 7, 8 and 12.
 *
 * These five fields — Prefix Year, Title Year, Sharaf Year, Place Visited Year and the Other
 * Sansta "Since" year — are Hijri (AH), not Gregorian. They used to offer 1950–2026 CE, which
 * read as a plausible year and silently stored the wrong calendar.
 *
 * The CEILING is deliberately not here. It is `lookups.current_hijri_year`, computed on the
 * server, so the list extends itself every Hijri year and a browser with a wrong clock cannot
 * widen it. Tab 9 keeps its own floor of 1400 AH, which FR-076 names explicitly.
 */
export const PROFILE_HIJRI_YEAR_MIN = 1401;

/** Descending year options, newest first, which is what a member usually wants. */
export function yearOptions(from: number, to: number, placeholder = "Select..."): SelectOption[] {
  const years: SelectOption[] = [{ value: "", label: placeholder }];
  for (let year = to; year >= from; year -= 1) {
    years.push({ value: String(year), label: String(year) });
  }
  return years;
}

/** Reads a numeric select value, treating the placeholder as "not set". */
export function toNullableId(raw: string): number | null {
  return raw === "" ? null : Number(raw);
}

/** Reads a numeric text input, treating blank as "not set" rather than zero. */
export function toNullableNumber(raw: string): number | null {
  if (raw.trim() === "") return null;
  const parsed = Number(raw);
  return Number.isFinite(parsed) ? parsed : null;
}

/**
 * BMI from height and weight, for live display as the member types.
 *
 * The stored value is generated by the database and is authoritative (FR-064); this only
 * fills the gap between typing and saving, so the field is not blank until a save. Returns
 * null on non-positive input, matching the generated column exactly.
 */
export function computeBmi(heightCm: number | null, weightKg: number | null): number | null {
  if (!heightCm || !weightKg || heightCm <= 0 || weightKg <= 0) return null;
  const metres = heightCm / 100;
  return Math.round((weightKg / (metres * metres)) * 100) / 100;
}

